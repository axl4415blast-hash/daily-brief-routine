WD = "月火水木金土日"
for year, hol in HOL.items():
    days=[]; d=dt.date(year,1,1)
    while d.year==year:
        s=d.isoformat()
        if d.weekday()<5 and s not in hol: days.append(s)
        d+=dt.timedelta(days=1)
    closed=[{"date":k,"reason":v,"weekday":WD[dt.date.fromisoformat(k).weekday()]} for k,v in sorted(hol.items())]
